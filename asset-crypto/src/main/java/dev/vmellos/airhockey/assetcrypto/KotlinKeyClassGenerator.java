package dev.vmellos.airhockey.assetcrypto;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.util.Locale;

/**
 * Generates an obfuscated Kotlin key provider that reconstructs the 256-bit vault master key from
 * rotated and XOR-masked {@code Long} literals without plaintext string secrets.
 */
public final class KotlinKeyClassGenerator {

    private KotlinKeyClassGenerator() {}

    /**
     * Emits Kotlin source code defining {@code internal object <className>} inside {@code packageName}.
     */
    public static String generateSource(
        String packageName,
        String className,
        String variantName,
        byte[] masterKey
    ) throws GeneralSecurityException {
        AssetKeyDerivation.validateMasterKey(masterKey);
        validateIdentifier(packageName, true);
        validateIdentifier(className, false);
        String safeVariant = variantName == null ? "default" : variantName;

        byte[] obfSeed = AssetKeyDerivation.hmacSha256(
            masterKey,
            ("airhockey.vault.kotlin-obf.v1:" + safeVariant).getBytes(StandardCharsets.UTF_8)
        );
        byte[] stream0 = AssetKeyDerivation.hmacSha256(obfSeed, new byte[] { 0x01 });
        byte[] stream1 = AssetKeyDerivation.hmacSha256(obfSeed, new byte[] { 0x02 });
        byte[] stream2 = AssetKeyDerivation.hmacSha256(obfSeed, new byte[] { 0x03 });

        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(packageName).append("\n\n");
        sb.append("/** Generated by :asset-crypto for variant ").append(safeVariant)
            .append(". Reconstructs the 256-bit vault key in memory without plaintext literals. */\n");
        sb.append("internal object ").append(className).append(" {\n\n");
        sb.append("    internal fun reconstructMasterKey(): ByteArray {\n");
        sb.append("        val out = ByteArray(32)\n");

        for (int i = 0; i < 4; i++) {
            long word = readLongBigEndian(masterKey, i * 8);
            long maskA = readLongBigEndian(stream0, i * 8);
            long maskB = readLongBigEndian(stream1, i * 8);
            int rawRot = (stream2[i * 4] & 0xFF) % 63 + 1;
            long encoded = Long.rotateLeft(word ^ maskA, rawRot) ^ maskB;

            sb.append("        val w").append(i).append(" = ((")
                .append(toKotlinUnsignedLongLiteral(encoded))
                .append(" xor ")
                .append(toKotlinUnsignedLongLiteral(maskB))
                .append(").rotateRight(").append(rawRot).append(") xor ")
                .append(toKotlinUnsignedLongLiteral(maskA))
                .append(")\n");
            sb.append("        putLongBigEndian(out, ").append(i * 8).append(", w").append(i).append(")\n");
        }

        sb.append("        return out\n");
        sb.append("    }\n\n");
        sb.append("    private fun putLongBigEndian(dest: ByteArray, offset: Int, value: Long) {\n");
        sb.append("        for (b in 0 until 8) {\n");
        sb.append("            dest[offset + b] = ((value ushr ((7 - b) * 8)) and 0xFFL).toByte()\n");
        sb.append("        }\n");
        sb.append("    }\n");
        sb.append("}\n");
        return sb.toString();
    }

    private static long readLongBigEndian(byte[] src, int offset) {
        long value = 0L;
        for (int b = 0; b < 8; b++) {
            value = (value << 8) | (src[offset + b] & 0xFFL);
        }
        return value;
    }

    private static String toKotlinUnsignedLongLiteral(long value) {
        return String.format(Locale.ROOT, "0x%016XuL.toLong()", value);
    }

    private static void validateIdentifier(String identifier, boolean allowDots) {
        if (identifier == null || identifier.isEmpty()) {
            throw new IllegalArgumentException("Identifier must not be blank.");
        }
        String regex = allowDots
            ? "^[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*$"
            : "^[A-Za-z_][A-Za-z0-9_]*$";
        if (!identifier.matches(regex)) {
            throw new IllegalArgumentException("Invalid Kotlin identifier: " + identifier);
        }
    }
}
